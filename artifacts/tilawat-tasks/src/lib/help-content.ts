// يفتح زر «؟» القسم المرتبط بالصفحة الحالية (العضو لا يُوجَّه لأقسام المدير).
export function helpSectionForRoute(path: string, isAdmin: boolean): HelpSection | null {
  const visible = HELP_SECTIONS.filter((s) => isAdmin || s.audience === "member");
  const match = visible
    .flatMap((s) => s.routes.map((route) => ({ s, route })))
    .filter(({ route }) => path === route || path.startsWith(`${route}/`))
    .sort((a, b) => b.route.length - a.route.length)[0];
  return match?.s ?? null;
}

